"""The 5 challenge targets (task A1): config/targets.yaml and the shared helpers.

The file is generated by `python -m serafim.validation.targets`; these tests read it
without any network call and check it against the challenge text and against itself.
"""

from pathlib import Path

import astropy.units as u
import numpy as np
import pytest
import yaml
from astropy.coordinates import SkyCoord
from astropy.time import Time

from serafim.validation import targets

ROOT = Path(__file__).resolve().parents[1]
TEXT = (ROOT / "config" / "targets.yaml").read_text(encoding="utf-8")
DOC = yaml.safe_load(TEXT)
BY_ID = {target["id"]: target for target in DOC["targets"]}
NOW = Time(DOC["now_utc"], scale="utc")

# From the challenge text: "WISE 0855 (a fast-moving brown dwarf Right Ascension
# 08h55m10.831s, declination -7d14m42.53s)".
CHALLENGE_WISE_0855 = SkyCoord("08h55m10.831s -07d14m42.53s", frame="icrs")

REQUIRED = {
    "id", "name", "kind", "simbad_id", "ra", "dec", "ref_epoch", "pmra_mas_yr", "pmdec_mas_yr",
    "parallax_mas", "ra_now", "dec_now", "mag", "n_frames", "frames_by_detector", "seasons",
    "motion", "saturation", "sources", "what", "expect",
}  # fmt: skip


def sky(ra, dec):
    return SkyCoord(ra * u.deg, dec * u.deg)


def per_target(test):
    return pytest.mark.parametrize("target", DOC["targets"], ids=lambda target: target["id"])(test)


# --- config/targets.yaml ---------------------------------------------------------------


def test_the_five_challenge_targets():
    assert list(BY_ID) == ["barnard", "eps_indi_b", "wise_0855", "rw_aur", "r_dra"]
    kinds = [target["kind"] for target in DOC["targets"]]
    assert kinds == ["motion", "spectrum", "motion", "brightness", "brightness"]


def test_settings_stay_above_the_generated_part():
    settings = yaml.safe_load(TEXT.split(targets.MARKER)[0])["settings"]
    assert {"cutout_size_deg", "collections", "seasons"} <= set(settings)
    assert TEXT.count(targets.MARKER) == 1


@per_target
def test_target_is_complete(target):
    assert REQUIRED <= set(target)
    assert target["kind"] in targets.KINDS


@per_target
def test_position_now_is_the_j2000_position_moved_to_now(target):
    moved = targets.propagate(target, NOW)
    assert sky(target["ra_now"], target["dec_now"]).separation(sky(moved.ra.deg, moved.dec.deg)) < (
        0.01 * u.arcsec
    )


def test_wise_0855_passes_through_the_challenge_position():
    years = np.arange(2009.0, 2012.0, 0.01)
    track = targets.propagate(BY_ID["wise_0855"], Time(years, format="jyear"))
    separation = sky(track.ra.deg, track.dec.deg).separation(CHALLENGE_WISE_0855).arcsec
    assert separation.min() < 1.0  # parallax alone is 0.44 arcsec
    assert 2010 <= years[np.argmin(separation)] < 2011


def test_wise_0855_is_no_longer_at_the_challenge_position():
    """Whoever types the challenge coordinates today needs a field wider than the offset."""
    offset = sky(BY_ID["wise_0855"]["ra_now"], BY_ID["wise_0855"]["dec_now"]).separation(
        CHALLENGE_WISE_0855
    )
    assert offset.arcmin > 2
    assert BY_ID["wise_0855"]["challenge_position"]["offset_now_arcmin"] == pytest.approx(
        offset.arcmin, abs=0.01
    )


def test_barnard_is_more_than_4_arcmin_from_its_j2000_position():
    barnard = BY_ID["barnard"]
    j2000 = sky(barnard["ra"], barnard["dec"])
    assert sky(barnard["ra_now"], barnard["dec_now"]).separation(j2000).arcmin > 4


@per_target
def test_seasons(target):
    seasons = target["seasons"]
    assert len(seasons) >= 2  # task D3: frames in at least 2 seasons
    assert [season["season"] for season in seasons] == list(range(1, len(seasons) + 1))
    starts = [season["start_utc"] for season in seasons]
    assert starts == sorted(starts)
    assert all(season["start_utc"] <= season["end_utc"] for season in seasons)
    assert sum(season["n_frames"] for season in seasons) == target["n_frames"]
    assert sum(target["frames_by_detector"].values()) == target["n_frames"]


@per_target
def test_saturation_was_checked_in_every_detector(target):
    checked = {row["detector"] for row in target["saturation"]}
    assert checked == set(target["frames_by_detector"])
    for row in target["saturation"]:
        assert 0 <= row["saturated"] <= row["checked"]


# --- Shared helpers ----------------------------------------------------------------------


def test_propagate_follows_the_proper_motion():
    star = {"ra": 10.0, "dec": 0.0, "pmra_mas_yr": 0.0, "pmdec_mas_yr": 1000.0, "parallax_mas": 100}
    later = targets.propagate(star, Time(2010.0, format="jyear"))
    assert later.dec.to_value(u.arcsec) == pytest.approx(10.0, abs=0.01)
    assert later.ra.deg == pytest.approx(10.0, abs=1e-6)


def test_split_seasons_cuts_at_gaps():
    assert targets.split_seasons([0, 1, 2, 40, 41, 100]).tolist() == [1, 1, 1, 2, 2, 3]


def test_split_seasons_cuts_long_runs_into_passes():
    times = np.arange(0, 400, 5.0)  # a frame every 5 days for 400 days, never a gap
    seasons = targets.split_seasons(times, gap_days=30, max_days=183)
    assert seasons.max() == 3
    assert (np.diff(seasons) >= 0).all()
    for season in np.unique(seasons):
        assert np.ptp(times[seasons == season]) <= 183


def test_split_seasons_keeps_the_input_order():
    assert targets.split_seasons([41, 0, 40, 1]).tolist() == [2, 1, 2, 1]
    assert targets.split_seasons([]).tolist() == []


def test_render_keeps_the_hand_edited_settings():
    head = "settings:\n  cutout_size_deg: 0.3  # edited\n\n"
    existing = head + targets.MARKER + "\ntargets: []\n"
    text = targets.render({"targets": [{"id": "x"}]}, existing)
    assert "cutout_size_deg: 0.3  # edited" in text
    assert text.count(targets.MARKER) == 1
    assert yaml.safe_load(text) == {"settings": {"cutout_size_deg": 0.3}, "targets": [{"id": "x"}]}


def test_render_starts_from_the_default_settings():
    text = targets.render({"targets": []}, None)
    assert yaml.safe_load(text)["settings"] == targets.read_settings(None)


def test_detector_from_the_bandpass_name():
    assert targets._detector("SPHEREx-D2") == 2
    with pytest.raises(ValueError):
        targets._detector("SPHEREx-D7")
