"""Guide texts of the 5 targets (task A3): web/texts/targets.json.

The file is generated by `python -m serafim.validation.guides` from config/targets.yaml;
these tests read both without any network call.
"""

import json
import re
from pathlib import Path

import pytest
import yaml

from serafim.validation import guides

ROOT = Path(__file__).resolve().parents[1]
DOCUMENT = yaml.safe_load((ROOT / "config" / "targets.yaml").read_text(encoding="utf-8"))
TARGETS = {target["id"]: target for target in DOCUMENT["targets"]}
FILE = ROOT / "web" / "texts" / "targets.json"
GUIDES = json.loads(FILE.read_text(encoding="utf-8"))
BY_ID = {guide["id"]: guide for guide in GUIDES["targets"]}

MAX_WORDS = 150  # ~1 minute of reading: the check in the plan is "understood in 1 minute"
JARGON = ("dipole", "psf", "photometry", "parallax", "arcsec", "ecliptic", "icrs", "j2000",
          "proper motion", "mas/yr")  # fmt: skip


def per_guide(test):
    return pytest.mark.parametrize("guide", GUIDES["targets"], ids=lambda guide: guide["id"])(test)


def reading(guide):
    """Everything a visitor reads in one guide."""
    how = guide["how_to_look"]["text"]
    return [guide["headline"], guide["what_it_is"], guide["what_to_look_at"], how,
            *guide["watch_out"]]  # fmt: skip


def test_the_file_is_what_the_generator_writes():
    """Nobody edits targets.json by hand: regenerate it when targets.yaml changes."""
    assert FILE.read_text(encoding="utf-8") == guides.render(DOCUMENT)


def test_check_mode_agrees(capsys):
    assert guides.main(["--check"]) == 0


def test_the_five_targets_in_order():
    assert list(BY_ID) == list(TARGETS)
    assert [guide["kind"] for guide in GUIDES["targets"]] == [
        target["kind"] for target in DOCUMENT["targets"]
    ]
    assert GUIDES["draft"] is True


@per_guide
def test_every_text_is_written(guide):
    for text in reading(guide):
        assert isinstance(text, str) and len(text.strip()) > 10
    assert guide["how_to_look"]["mode"] in {mode["id"] for mode in GUIDES["modes"]}


@per_guide
def test_a_guide_reads_in_a_minute(guide):
    words = re.findall(r"[\w'.-]+", " ".join(reading(guide)))
    assert len(words) <= MAX_WORDS


@per_guide
def test_no_jargon(guide):
    text = " ".join(reading(guide)).lower()
    assert [word for word in JARGON if word in text] == []


@per_guide
def test_facts_come_from_targets_yaml(guide):
    target, facts = TARGETS[guide["id"]], guide["facts"]
    assert (facts["ra_now"], facts["dec_now"]) == (target["ra_now"], target["dec_now"])
    assert facts["frames"] == target["n_frames"]
    assert facts["seasons"] == len(target["seasons"])
    if "shift_pixels_first_to_last_season" in facts:
        shift = target["motion"]["shift_px_first_to_last_season"]
        assert facts["shift_pixels_first_to_last_season"] == shift
        assert f"{shift:.1f} pixels" in guide["what_to_look_at"] + " ".join(guide["watch_out"])
    if "distance_light_years" in facts:
        distance = 1000 / target["parallax_mas"] * guides.LIGHT_YEARS_PER_PARSEC
        assert facts["distance_light_years"] == pytest.approx(distance, abs=0.01)
        assert f"{distance:.0f} light-years" in guide["what_it_is"]


@per_guide
def test_recommended_detectors_have_frames(guide):
    seen = {int(detector) for detector in TARGETS[guide["id"]]["frames_by_detector"]}
    assert set(guide["how_to_look"]["detectors"]) <= seen


def test_wise_0855_opens_where_spherex_sees_it():
    """The visibility check (docs/visibility.md) sees it in D6, and in D5 with every season."""
    how = BY_ID["wise_0855"]["how_to_look"]
    assert how["detectors"] == [6, 5]  # the first one is the one the viewer opens
    assert how["mode"] == "all_seasons"
    assert BY_ID["wise_0855"]["facts"]["seen_in_detectors"] == [6, 5]


def test_wise_0855_warns_about_the_star_it_passes():
    """In D1-D4 the dot at its position is a G = 16.3 star, not the brown dwarf."""
    facts = BY_ID["wise_0855"]["facts"]["neighbour_star"]
    pixels = {int(season): value for season, value in facts["pixels_by_season"].items()}
    assert pixels == pytest.approx({1: 1.92, 2: 1.27, 3: 0.75}, abs=0.05)  # it is closing in
    assert pixels == guides.neighbour_pixels(TARGETS["wise_0855"])
    warning = " ".join(BY_ID["wise_0855"]["watch_out"])
    assert "not WISE 0855" in warning and "detectors 1 to 4" in warning


def test_barnard_is_shown_where_its_saturated_center_is_smallest():
    assert BY_ID["barnard"]["how_to_look"]["detectors"] == [5, 6]


def test_saturated_targets_say_so():
    for target_id, guide in BY_ID.items():
        saturated = bool(guides.saturated_detectors(TARGETS[target_id]))
        assert saturated == any("saturated" in text for text in guide["watch_out"]), target_id


def test_rw_aur_does_not_saturate_every_frame_of_detector_1():
    text = " ".join(BY_ID["rw_aur"]["watch_out"])
    assert "sometimes in detector 1" in text
    assert BY_ID["rw_aur"]["how_to_look"]["detectors"] == [1]


def test_motion_directions_on_a_north_up_image():
    assert guides.direction(TARGETS["barnard"]) == ("north", "up")  # pm Dec +10.4"/yr
    assert guides.direction(TARGETS["wise_0855"]) == ("west", "to the right")  # pm RA -8.1"/yr


def test_flags_match_the_bits_measured_in_d1():
    """Every MSKN* name in docs/real_fits.md, with its bit, and nothing else."""
    doc = (ROOT / "docs" / "real_fits.md").read_text(encoding="utf-8")
    table = doc.split("## FLAGS bits")[1].split("\n## ")[0]
    measured = {
        (int(bit), name.strip("*"))
        for bit, name in re.findall(r"\|\s*(\d+)\s*\|\s*\**([A-Z_]+)\**\s*", table)
    }
    assert {(flag["bit"], flag["name"]) for flag in GUIDES["flags"]} == measured
    by_name = {flag["name"]: flag for flag in GUIDES["flags"]}
    assert by_name["SOURCE"]["in_sums"] == guides.KEPT  # never mask SOURCE
    assert by_name["OVERFLOW"]["in_sums"] == by_name["NONLINEAR"]["in_sums"] == guides.LEFT_OUT


def test_detectors_match_the_edges_measured_in_d1():
    edges = [(row["detector"], row["from_um"], row["to_um"]) for row in GUIDES["detectors"]]
    assert edges == [
        (1, 0.746, 1.117), (2, 1.103, 1.650), (3, 1.630, 2.435),
        (4, 2.403, 3.847), (5, 3.811, 4.430), (6, 4.412, 5.010),
    ]  # fmt: skip


def test_layers_are_the_catalogs_of_task_a2():
    from serafim.validation import layers

    assert [layer["id"] for layer in GUIDES["layers"]] == list(layers.MAG_BANDS)
