"""The 5 SPHEREx challenge targets (task A1, AI & validation).

`python -m serafim.validation.targets` writes config/targets.yaml from queries anyone
can repeat, so no number in that file is typed by hand:

- SIMBAD: position (ICRS, epoch J2000), proper motion, parallax, V, J, H and K.
- AllWISE, or CatWISE2020 if AllWISE has no match: W1 and W2 at the WISE epoch.
- IRSA SIA: every SPHEREx frame of the target, grouped into seasons.
- Small cutouts (data/targets/): FLAGS on the target pixel, to see which detectors saturate.

Only the part of the file below MARKER is rewritten; the settings above it are edited by
hand. Queries are cached in data/catalog_cache/, so a second run is fast.

propagate() and split_seasons() are shared with the pipeline, so a target position and a
season mean the same thing in every layer.
"""

