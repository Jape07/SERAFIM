# --- Shared with the pipeline ------------------------------------------------------


def propagate(target: dict, when: Time) -> SkyCoord:
    """Position of a target at `when`, from its J2000 position, proper motion and parallax.

    Barycentric: the parallax shift seen from SPHEREx (at most the parallax itself, 0.55
    arcsec for Barnard's Star) and the radial velocity are left out; both are far below
    one 6.15 arcsec pixel.
    """
    parallax = target.get("parallax_mas") or 0.0
    distance = Distance(parallax=parallax * u.mas) if parallax > 0 else 10 * u.kpc
    start = SkyCoord(
        ra=target["ra"] * u.deg,
        dec=target["dec"] * u.deg,
        pm_ra_cosdec=target["pmra_mas_yr"] * u.mas / u.yr,
        pm_dec=target["pmdec_mas_yr"] * u.mas / u.yr,
        distance=distance,
        obstime=Time("J2000"),
    )
    with warnings.catch_warnings():
        warnings.simplefilter("ignore", ErfaWarning)
        return start.apply_space_motion(new_obstime=when)


def split_seasons(times_mjd, gap_days: float = 30.0, max_days: float = 183.0) -> np.ndarray:
    """Season number (1, 2, ...) of each frame time, in the same order as the input.

    A new season starts after more than gap_days without frames. A run longer than
    max_days (targets near the ecliptic poles are observed all year) is cut into equal
    parts of at most max_days: one per ~6-month SPHEREx all-sky pass.
    """
    t = np.asarray(times_mjd, dtype=float)
    if t.size == 0:
        return np.array([], dtype=int)
    order = np.argsort(t, kind="stable")
    sorted_t = t[order]
    labels = np.empty(t.size, dtype=int)
    next_label = 1
    start = 0
    for end in [*(np.flatnonzero(np.diff(sorted_t) > gap_days) + 1), t.size]:
        run = sorted_t[start:end]
        parts = max(1, int(np.ceil((run[-1] - run[0]) / max_days)))
        edges = np.linspace(run[0], run[-1], parts + 1)
        part = np.clip(np.searchsorted(edges, run, side="right") - 1, 0, parts - 1)
        labels[start:end] = next_label + part
        next_label += parts
        start = end
    labels = np.unique(labels, return_inverse=True)[1] + 1  # no empty season numbers
    result = np.empty(t.size, dtype=int)
    result[order] = labels
    return result


# --- Queries (cached) ------------------------------------------------------------------


def simbad_object(identifier: str) -> dict:
    """SIMBAD basic data for one object, found by any of its identifiers."""
    quoted = identifier.replace("'", "''")
    adql = f"""
        SELECT b.main_id, b.ra, b.dec, b.pmra, b.pmdec, b.plx_value, b.otype, b.sp_type,
               b.coo_bibcode, b.pm_bibcode, b.plx_bibcode, f.V, f.J, f.H, f.K
        FROM ident AS i JOIN basic AS b ON i.oidref = b.oid
        LEFT JOIN allfluxes AS f ON b.oid = f.oidref
        WHERE i.id = '{quoted}'
    """

    def fetch() -> pd.DataFrame:
        rows = catalogs._run_simbad(adql)[0].to_pandas()
        if len(rows) != 1:
            raise LookupError(f"SIMBAD returned {len(rows)} objects for {identifier!r}")
        return rows

    return catalogs._cached("simbad_object", {"id": identifier}, fetch).iloc[0].to_dict()


def wise_photometry(target: dict) -> dict:
    """W1 and W2: the nearest AllWISE source at the WISE epoch, or CatWISE2020 if none."""
    pm_arcsec_yr = float(np.hypot(target["pmra_mas_yr"], target["pmdec_mas_yr"])) / 1000
    radius = round(max(WISE_MATCH_ARCSEC, pm_arcsec_yr), 2)  # each source's epoch is ~1 yr wide
    for catalog, table, name_column, epoch in WISE_CATALOGS:
        position = _plain(propagate(target, epoch))
        params = {
            "table": table,
            "ra": round(float(position.ra.deg), 6),
            "dec": round(float(position.dec.deg), 6),
            "radius_arcsec": radius,
        }
        rows = catalogs._cached(
            "wise", params, lambda table=table, position=position: _scs(table, position, radius)
        )
        if len(rows):
            found = SkyCoord(rows["ra"].to_numpy() * u.deg, rows["dec"].to_numpy() * u.deg)
            separation = found.separation(position).arcsec
            best = rows.iloc[int(np.argmin(separation))]
            return {
                "catalog": catalog,
                "name": str(best[name_column]),
                "W1": _number(best["w1mpro"]),
                "W2": _number(best["w2mpro"]),
                "match_arcsec": round(float(separation.min()), 2),
            }
    return {"catalog": None, "name": None, "W1": None, "W2": None, "match_arcsec": None}


def spherex_frames(center: SkyCoord, collections: list[str]) -> pd.DataFrame:
    """Every SPHEREx frame that covers `center`, one row per exposure, in time order.

    When an exposure is in several collections, the first collection in the list wins.
    """
    icrs = _plain(center)
    params = {
        "ra": round(float(icrs.ra.deg), 5),
        "dec": round(float(icrs.dec.deg), 5),
        "collections": list(collections),
    }
    return catalogs._cached("spherex_sia", params, lambda: _query_frames(icrs, collections))


def _scs(table: str, position: SkyCoord, radius_arcsec: float) -> pd.DataFrame:
    service = pyvo.dal.SCSService(IRSA_SCS.format(table=table), session=catalogs._TimeoutSession())
    result = service.search(pos=position, radius=radius_arcsec / 3600).to_table()
    wanted = ("designation", "source_name", "ra", "dec", "w1mpro", "w2mpro")
    return result[[name for name in result.colnames if name in wanted]].to_pandas()


FRAME_COLUMNS = ["obs_id", "collection", "t_mid_mjd", "detector", "bandpass", "em_min_um",
                 "em_max_um", "access_url"]  # fmt: skip


def _query_frames(center: SkyCoord, collections: list[str]) -> pd.DataFrame:
    from astroquery.ipac.irsa import Irsa

    parts = []
    for collection in collections:
        table = _retry(
            f"SIA {collection}", Irsa.query_sia, pos=(center, 0.001 * u.deg), collection=collection
        )
        if len(table) == 0:
            continue
        bandpass = np.asarray(table["energy_bandpassname"]).astype(str)
        t_mid = (np.asarray(table["t_min"], float) + np.asarray(table["t_max"], float)) / 2
        parts.append(
            pd.DataFrame(
                {
                    "obs_id": np.asarray(table["obs_id"]).astype(str),
                    "collection": collection,
                    "t_mid_mjd": t_mid,
                    "detector": [_detector(name) for name in bandpass],
                    "bandpass": bandpass,
                    "em_min_um": np.asarray(table["em_min"], float) * 1e6,
                    "em_max_um": np.asarray(table["em_max"], float) * 1e6,
                    "access_url": np.asarray(table["access_url"]).astype(str),
                }
            )
        )
    if not parts:
        return pd.DataFrame({name: [] for name in FRAME_COLUMNS})
    frames = pd.concat(parts, ignore_index=True).drop_duplicates("obs_id")
    return frames.sort_values("t_mid_mjd", ignore_index=True)[FRAME_COLUMNS]


def _detector(bandpass: str) -> int:
    """Detector number from the SIA bandpass name: 'SPHEREx-D2' -> 2."""
    match = re.fullmatch(r"SPHEREx-D([1-6])", bandpass.strip())
    if not match:
        raise ValueError(f"unknown SPHEREx bandpass name: {bandpass!r}")
    return int(match.group(1))


# --- Saturation ---------------------------------------------------------------------------


def saturation_by_detector(target: dict, frames: pd.DataFrame, out_dir: Path) -> list[dict]:
    """FLAGS on the target pixel in up to 2 frames per detector (first and last season)."""
    picks = []
    for _, group in frames.groupby("detector"):
        for season in sorted({group["season"].min(), group["season"].max()}):
            part = group[group["season"] == season]
            middle = part["t_mid_mjd"].median()
            picks.append(part.iloc[int(np.argmin(np.abs(part["t_mid_mjd"].to_numpy() - middle)))])
    if not picks:
        return []
    rows = list(pd.DataFrame(picks).itertuples(index=False))
    with ThreadPoolExecutor(8) as pool:
        results = pool.map(lambda row: _flags_on_target(target, row, out_dir), rows)
        checked = [result for result in results if result]
    summary = []
    for detector in sorted({c["detector"] for c in checked}):
        mine = [c for c in checked if c["detector"] == detector]
        summary.append(
            {
                "detector": detector,
                "checked": len(mine),
                "saturated": sum(c["saturated"] for c in mine),
                "flags": sorted(set().union(*(c["flags"] for c in mine))),
            }
        )
    return summary


def _flags_on_target(target: dict, frame, out_dir: Path) -> dict | None:
    position = _plain(propagate(target, Time(frame.t_mid_mjd, format="mjd")))
    path = out_dir / f"{frame.obs_id}.fits"
    if not path.exists():
        url = (
            f"{frame.access_url}?center={position.ra.deg:.6f},{position.dec.deg:.6f}d"
            f"&size={FLAGS_CUTOUT_DEG}"
        )
        try:
            content = _retry(f"cutout {frame.obs_id}", _download_fits, url)
        except Exception as error:  # one missing cutout must not stop the others
            log.warning("cutout %s skipped: %s", frame.obs_id, error)
            return None
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(content)

    with fits.open(path) as hdul, warnings.catch_warnings():
        warnings.simplefilter("ignore")  # FITSFixedWarning on SPHEREx headers
        x, y = WCS(hdul["IMAGE"].header).world_to_pixel(position)
        column, row = int(round(float(x))), int(round(float(y)))
        flags = hdul["FLAGS"]
        box = flags.data[max(row - 1, 0) : row + 2, max(column - 1, 0) : column + 2]
        bits = [(key, value) for key, value in flags.header.items() if key.startswith("MSKN")]
        names = {int(key[4:]): str(value) for key, value in bits}
    if box.size == 0:
        log.warning("target outside cutout %s", frame.obs_id)
        return None
    value = int(np.bitwise_or.reduce(box.astype(np.int64).ravel()))
    seen = sorted(name for bit, name in names.items() if value >> bit & 1)
    return {
        "detector": int(frame.detector),
        "saturated": any(name in SATURATION_FLAGS for name in seen),
        "flags": seen,
    }


def _download_fits(url: str) -> bytes:
    response = catalogs._TimeoutSession().get(url)
    response.raise_for_status()
    if not response.content.startswith(b"SIMPLE"):
        raise ValueError(f"not a FITS file: {url}")
    return response.content


# --- Building the file -------------------------------------------------------------------


def build_target(spec: Spec, now: Time, settings: dict, cutout_dir: Path | None) -> dict:
    """Everything config/targets.yaml says about one target."""
    simbad = simbad_object(spec.simbad_id)
    target = {
        "id": spec.id,
        "name": spec.name,
        "kind": spec.kind,
        "simbad_id": str(simbad["main_id"]).strip(),
        "simbad_type": str(simbad["otype"]).strip(),
        "spectral_type": _text(simbad["sp_type"]),
        "ra": round(float(simbad["ra"]), 7),
        "dec": round(float(simbad["dec"]), 7),
        "ref_epoch": "J2000",
        "pmra_mas_yr": round(float(simbad["pmra"]), 3),
        "pmdec_mas_yr": round(float(simbad["pmdec"]), 3),
        "parallax_mas": round(float(simbad["plx_value"]), 4),
    }
    now_position = _plain(propagate(target, now))
    target["ra_now"] = round(float(now_position.ra.deg), 7)
    target["dec_now"] = round(float(now_position.dec.deg), 7)
    if spec.challenge_position:
        given = SkyCoord(spec.challenge_position, frame="icrs")
        target["challenge_position"] = {
            "ra": round(float(given.ra.deg), 7),
            "dec": round(float(given.dec.deg), 7),
            "offset_now_arcmin": round(float(now_position.separation(given).arcmin), 2),
        }

    wise = wise_photometry(target)
    target["mag"] = {band: _number(simbad[band]) for band in ("V", "J", "H", "K")}
    target["mag"].update(W1=wise["W1"], W2=wise["W2"])

    frames = spherex_frames(now_position, settings["collections"]).copy()
    seasons = settings["seasons"]
    frames["season"] = split_seasons(frames["t_mid_mjd"], seasons["gap_days"], seasons["max_days"])
    target["n_frames"] = int(len(frames))
    counts = frames["detector"].value_counts().sort_index()
    target["frames_by_detector"] = {int(detector): int(n) for detector, n in counts.items()}
    target["seasons"] = _seasons(target, frames)

    pm_arcsec_yr = float(np.hypot(target["pmra_mas_yr"], target["pmdec_mas_yr"])) / 1000
    j2000 = SkyCoord(target["ra"] * u.deg, target["dec"] * u.deg)
    target["motion"] = {
        "pm_total_arcsec_yr": round(pm_arcsec_yr, 3),
        "shift_since_j2000_arcmin": round(float(now_position.separation(j2000).arcmin), 2),
        "shift_px_per_year": round(pm_arcsec_yr / PIXEL_SCALE_ARCSEC, 3),
        "shift_px_first_to_last_season": (
            target["seasons"][-1]["shift_from_first_px"] if target["seasons"] else None
        ),
    }
    target["saturation"] = (
        saturation_by_detector(target, frames, cutout_dir / spec.id) if cutout_dir else None
    )
    target["sources"] = {
        "position": _text(simbad["coo_bibcode"]),
        "proper_motion": _text(simbad["pm_bibcode"]),
        "parallax": _text(simbad["plx_bibcode"]),
        "wise": f"{wise['catalog']} {wise['name']} ({wise['match_arcsec']} arcsec)"
        if wise["catalog"]
        else None,
    }
    target["what"] = spec.what
    target["expect"] = spec.expect
    log.info("%s: %d frames in %d seasons", spec.id, len(frames), len(target["seasons"]))
    return target


def _seasons(target: dict, frames: pd.DataFrame) -> list[dict]:
    out = []
    first = None
    for season, group in frames.groupby("season", sort=True):
        mean = Time(float(group["t_mid_mjd"].mean()), format="mjd")
        position = _plain(propagate(target, mean))
        first = position if first is None else first
        out.append(
            {
                "season": int(season),
                "start_utc": _iso(group["t_mid_mjd"].min()),
                "end_utc": _iso(group["t_mid_mjd"].max()),
                "mean_utc": _iso(mean.mjd),
                "n_frames": int(len(group)),
                "detectors": sorted(int(d) for d in group["detector"].unique()),
                "ra": round(float(position.ra.deg), 7),
                "dec": round(float(position.dec.deg), 7),
                "shift_from_first_px": round(
                    float(position.separation(first).arcsec) / PIXEL_SCALE_ARCSEC, 2
                ),
            }
        )
    return out


def render(document: dict, existing: str | None) -> str:
    """The new file: the hand-edited head of `existing` (or DEFAULT_HEAD) and the document."""
    if existing and MARKER in existing:
        head = existing.split(MARKER)[0].rstrip() + "\n\n"
    else:
        head = DEFAULT_HEAD + "\n"
    body = yaml.safe_dump(document, sort_keys=False, width=100, default_flow_style=None)
    return f"{head}{MARKER}\n{body}"


def read_settings(text: str | None) -> dict:
    head = text.split(MARKER)[0] if text and MARKER in text else DEFAULT_HEAD
    return yaml.safe_load(head)["settings"]


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        prog="python -m serafim.validation.targets",
        description="Write config/targets.yaml from SIMBAD, AllWISE/CatWISE and IRSA.",
    )
    parser.add_argument("--out", type=Path, default=TARGETS_PATH)
    parser.add_argument("--now", help="UTC date for ra_now/dec_now (default: today).")
    parser.add_argument("--no-flags", action="store_true", help="Skip the FLAGS cutouts.")
    args = parser.parse_args(argv)
    log_format = "%(asctime)s %(levelname)s %(name)s: %(message)s"
    logging.basicConfig(level=logging.INFO, format=log_format)

    now = Time(args.now or Time.now().utc.isot[:10], scale="utc")
    existing = args.out.read_text(encoding="utf-8") if args.out.exists() else None
    settings = read_settings(existing)
    cutout_dir = None if args.no_flags else CUTOUT_DIR
    targets = [build_target(spec, now, settings, cutout_dir) for spec in SPECS]
    document = {"now_utc": now.isot[:10], "targets": targets}
    args.out.write_text(render(document, existing), encoding="utf-8")
    log.info("wrote %s", args.out)
    return 0


# --- Small helpers -------------------------------------------------------------------------


def _retry(what: str, function, *args, **kwargs):
    for attempt in range(1, ATTEMPTS + 1):
        try:
            return function(*args, **kwargs)
        except Exception as error:  # any failure of a remote service counts
            if attempt == ATTEMPTS:
                raise
            log.warning("%s failed (attempt %d/%d): %s", what, attempt, ATTEMPTS, error)
            time.sleep(WAIT_S * attempt)
    raise AssertionError("unreachable")


def _plain(coord: SkyCoord) -> SkyCoord:
    """Only RA and Dec (ICRS), so separations and WCS lookups ignore epochs and motions."""
    icrs = coord.icrs
    return SkyCoord(ra=icrs.ra, dec=icrs.dec, frame="icrs")


def _number(value) -> float | None:
    try:
        number = float(value)
    except (TypeError, ValueError):
        return None
    return None if np.isnan(number) else round(number, 3)


def _text(value) -> str | None:
    if value is None or (isinstance(value, float) and np.isnan(value)):
        return None
    text = str(value).strip()
    return text or None


def _iso(mjd) -> str:
    return Time(float(mjd), format="mjd", scale="utc").isot[:16]


if __name__ == "__main__":
    raise SystemExit(main())
