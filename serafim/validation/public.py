"""Review of the published site (task A8): what the jury sees, checked like the local gold.

    python -m serafim.validation.public [--site URL] [--out data/public_gold]

1. Downloads the gold the site serves (the 7 tables, meta.json and every PNG they name) and
   checks it with validate_gold().
2. Compares it with the local gold: frames, sums and differences per target, and whether every
   catalog layer is there (a publish run while an archive is down leaves a layer out).
3. Runs the verification of task A6 and the marker check of task A8 on it (reports in --out; they
   use the local silver sums for the S/N, so a frame only one side has can move a number a bit).
4. Writes docs/mvp_review.md: the checklist for a person to walk the site, one link per target
   that opens exactly what its guide says, and what must be seen there.
"""

from __future__ import annotations

import argparse
import concurrent.futures
import json
import logging
import urllib.request
from pathlib import Path

import pandas as pd

from serafim import contract
from serafim.validation import targets

log = logging.getLogger(__name__)

SITE = "https://jape07.github.io/SERAFIM/"
OUT_DIR = targets.ROOT / "data" / "public_gold"
LOCAL_GOLD = targets.ROOT / "data" / "gold"
CHECKLIST_PATH = targets.ROOT / "docs" / "mvp_review.md"
LAYERS = ("gaia", "catwise", "simbad", "skybot")
WORKERS = 8


def fetch(url: str, path: Path) -> bool:
    path.parent.mkdir(parents=True, exist_ok=True)
    try:
        urllib.request.urlretrieve(url, path)
        return True
    except OSError as error:
        log.debug("%s: %s", url, error)
        return False


def download(site: str = SITE, out: Path = OUT_DIR) -> dict:
    """The published gold into `out`; returns what could not be fetched."""
    base = site.rstrip("/") + "/gold/"
    missing = [name for name in [*contract.GOLD_TABLES, "meta.json"]
               if not fetch(base + name, out / name)]  # fmt: skip
    if missing:
        raise RuntimeError(f"the site does not serve {missing}")
    sums = pd.read_parquet(out / "sums.parquet")
    differences = pd.read_parquet(out / "differences.parquet")
    pngs = set(sums["png"]) | set(differences["png"])
    for target_id, part in sums[(sums["detector"] >= 1) & (sums["season"] >= 1)].groupby(
        "target_id"
    ):
        pngs |= {contract.color_png(target_id, int(s)) for s in part["season"].unique()}
    with concurrent.futures.ThreadPoolExecutor(WORKERS) as pool:
        got = dict(zip(sorted(pngs), pool.map(lambda p: fetch(base + p, out / p), sorted(pngs)),
                       strict=True))  # fmt: skip
    return {"png_missing": sorted(p for p, ok in got.items() if not ok)}


def compare(public: dict[str, pd.DataFrame], local: dict[str, pd.DataFrame]) -> list[str]:
    """Differences that matter between the published and the local gold, in words."""
    notes = []
    for name in ("frames", "sums", "differences"):
        a = public[name].groupby("target_id").size()
        b = local[name].groupby("target_id").size() if len(local[name]) else pd.Series(dtype=int)
        for target_id in sorted(set(a.index) | set(b.index)):
            if a.get(target_id, 0) != b.get(target_id, 0):
                notes.append(f"{name}: {target_id} has {a.get(target_id, 0)} published, "
                             f"{b.get(target_id, 0)} local")  # fmt: skip
    layers = public["catalogs"].groupby("target_id")["catalog"].unique()
    for target_id, present in layers.items():
        absent = [layer for layer in ("gaia", "catwise", "simbad") if layer not in present]
        if absent:
            notes.append(f"catalogs: {target_id} has no {', '.join(absent)} layer on the site")
    return notes


def link(site: str, guide: dict) -> str:
    """The viewer URL that opens exactly what the guide says."""
    how = guide["how_to_look"]
    seasons = how["seasons"]
    if how["mode"] == "difference":
        season = f"{seasons[0]}-{seasons[-1]}"
    elif how["mode"] == "all_seasons":
        season = "0"
    else:
        season = str(seasons[0])
    query = (f"target={guide['id']}&detector={how['detectors'][0]}&season={season}"
             f"&mode={how['mode']}&layers={','.join(LAYERS)}")  # fmt: skip
    return f"{site.rstrip('/')}/index.html?{query}#visor"


def checklist(
    site: str, guides: dict, meta: dict, notes: list[str], verified: dict, markers: dict
) -> str:
    """docs/mvp_review.md: what a person checks on the published site."""  # fmt: skip
    run = str(meta.get("run_date_utc", ""))[:16]
    same = "- Same frames, sums, differences and layers as the local gold."
    lines = [
        "# Review of the published site (task A8)",
        "",
        "Generated by `python -m serafim.validation.public` from the gold the site serves"
        f" (commit `{meta.get('commit', '')[:7]}`, run {run} UTC,"
        f" {meta.get('n_frames', '?')} frames).",
        "",
        "## Automatic checks on the published gold",
        "",
        "- validate_gold(): passes (the download stops if it does not).",
        *[f"- Verification (A6), {t}: {v['status']}" for t, v in verified.items() if t != "gold"],
        *[f"- Markers (A8), {t}: {m['out_of_place']} out of place" for t, m in markers.items()],
        *([f"- ⚠️ {note}" for note in notes] or [same]),
        "",
        "## Walk the site",
        "",
        "Open each link (it opens what the guide says) and tick what you see. Write down anything",
        "that looks wrong, with a screenshot.",
        "",
    ]  # fmt: skip
    for guide in guides.values():
        how = guide["how_to_look"]
        cuts = guide.get("markers", {}).get("default_max_mag", {})
        lines += [
            f"### {guide['name']}",
            "",
            f"[Open in the viewer]({link(site, guide)}): detector {how['detectors'][0]}, "
            f"mode `{how['mode']}`, seasons {how['seasons']}.",
            "",
            f"- [ ] The guide reads: “{guide['headline']}”, and the text matches what you see: "
            f"{guide['what_to_look_at']}",
            "- [ ] The image is the one named above, north up, and the slider moves through the "
            "seasons.",
            f"- [ ] Markers sit on stars, only inside the image; Gaia down to G "
            f"{cuts.get('gaia', '—')}, CatWISE down to W2 {cuts.get('catwise', '—')} at first.",
            "- [ ] The target's own marker (SIMBAD) sits on it in every season.",
        ]  # fmt: skip
        if guide["facts"].get("saturated_detectors"):
            lines.append("- [ ] The saturated badge shows and the center is painted brightest.")
        if guide["kind"] in ("motion", "spectrum"):
            lines.append("- [ ] Its spectrum shows; flagged points are hollow.")
        lines.append("")
    lines += [
        "## Two coordinates that are not targets",
        "",
        "Waits for task D10 (a new target by coordinates).",
        "",
    ]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    from serafim.validation import markers, verification

    parser = argparse.ArgumentParser(prog="python -m serafim.validation.public")
    parser.add_argument("--site", default=SITE)
    parser.add_argument("--out", type=Path, default=OUT_DIR)
    parser.add_argument("--checklist", type=Path, default=CHECKLIST_PATH)
    args = parser.parse_args(argv)
    logging.basicConfig(level=logging.INFO, format="%(levelname)s %(name)s: %(message)s")

    fetched = download(args.site, args.out)
    contract.validate_gold(args.out)
    log.info("published gold valid; %d PNGs not served (color images of incomplete seasons)",
             len(fetched["png_missing"]))  # fmt: skip
    public, meta = verification.read_gold(args.out)
    local, _ = verification.read_gold(LOCAL_GOLD)
    notes = compare(public, local)
    for note in notes:
        log.warning(note)

    verification.main(["--gold", str(args.out), "--report", str(args.out / "verification.md"),
                       "--summary", str(args.out / "verification.json")])  # fmt: skip
    markers.main(["--gold", str(args.out), "--report", str(args.out / "markers.md"),
                  "--summary", str(args.out / "markers.json"),
                  "--images", str(args.out / "img")])  # fmt: skip
    verified = json.loads((args.out / "verification.json").read_text(encoding="utf-8"))
    checked = json.loads((args.out / "markers.json").read_text(encoding="utf-8"))
    guides = {g["id"]: g for g in
              json.loads(markers.GUIDES_PATH.read_text(encoding="utf-8"))["targets"]}  # fmt: skip
    args.checklist.write_text(checklist(args.site, guides, meta, notes, verified, checked),
                              encoding="utf-8", newline="\n")  # fmt: skip
    log.info("wrote %s", args.checklist)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
