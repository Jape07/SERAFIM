"""Load config/targets.yaml: the 5 challenge targets and every pipeline setting.

The `settings` block at the top is edited by hand; the `targets` list below the
marker line is generated by `python -m serafim.validation.targets` (AI & validation).
"""

from __future__ import annotations

from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
CONFIG_PATH = ROOT / "config" / "targets.yaml"


def load_config(path: Path | None = None) -> dict:
    """Return the config as a dict with the keys `settings` and `targets`."""
    with open(path or CONFIG_PATH, encoding="utf-8") as file:
        return yaml.safe_load(file)
