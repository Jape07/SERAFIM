export function lang() {
  return localStorage.getItem("serafim-lang") === "es" ? "es" : "en";
}

export function t(key, vars) {
  const pack = PACKS[lang()] || PACKS.en;
  let text = pack[key] ?? PACKS.en[key] ?? key;
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      text = text.replaceAll(`{${name}}`, String(value));
    }
  }
  return text;
}

export function apply(root = document) {
  document.documentElement.lang = lang();
  for (const node of root.querySelectorAll("[data-i18n]")) {
    const value = t(node.dataset.i18n);
    const attr = node.dataset.i18nAttr;
    if (attr) node.setAttribute(attr, value);
    else node.textContent = value;
  }
  const toggle = document.querySelector("#lang");
  if (toggle) {
    toggle.textContent = lang() === "en" ? "ES" : "EN";
    toggle.setAttribute("aria-pressed", lang() === "es" ? "true" : "false");
  }
  const themeLabel = document.querySelector("#theme-label");
  if (themeLabel) {
    const dark = document.documentElement.dataset.theme === "dark";
    themeLabel.textContent = dark ? t("themeDark") : t("themeLight");
  }
}

export function onChange(listener) {
  document.addEventListener("serafim-lang", listener);
}

document.querySelector("#lang")?.addEventListener("click", () => {
  localStorage.setItem("serafim-lang", lang() === "en" ? "es" : "en");
  apply();
  document.dispatchEvent(new Event("serafim-lang"));
});
